// Writes the Lucide icons the Flutter app uses to app/lib/design/lucide.dart, from the same lucide-react
// package Storybook uses, so both draw identical geometry. Usage: node design-system/build-icons.mjs
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const icons = ['arrow-left', 'arrow-right', 'calendar', 'map-pin', 'euro', 'plus', 'x', 'star', 'check', 'clock', 'banknote', 'truck', 'globe', 'phone', 'copy', 'user-plus', 'map-pin-plus', 'chevron-left', 'circle-check', 'scan-line', 'receipt', 'chevron-up', 'bed-double', 'vote', 'chevron-down'];
const camel = s => s.replace(/-([a-z])/g, (_, c) => c.toUpperCase());

const out = [
  '// Generated by design-system/build-icons.mjs from lucide-react (the icons Storybook uses). Do not edit.',
  '',
  '/// SVG bodies (24 × 24 view box) of the Lucide icons in the app. Draw them with `LucideIcon`.',
  'abstract final class Lucide {',
];
for (const name of icons) {
  const mod = await import(pathToFileURL(join(root, `storybook/node_modules/lucide-react/dist/esm/icons/${name}.mjs`)).href);
  const body = mod.__iconData.node
    .map(([tag, attrs]) => `<${tag} ${Object.entries(attrs).filter(([k]) => k !== 'key').map(([k, v]) => `${k}="${v}"`).join(' ')}/>`)
    .join('');
  out.push(`  static const ${camel(name)} = '${body}';`);
}
out.push('}');
writeFileSync(join(root, 'app/lib/design/lucide.dart'), out.join('\n') + '\n');
console.log(`wrote app/lib/design/lucide.dart (${icons.length} icons)`);
