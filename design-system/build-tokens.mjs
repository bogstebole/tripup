// Builds the token files for Storybook (CSS) and the Flutter app (Dart, and Android's launch colors) from design-system/tokens.json.
// Usage: node design-system/build-tokens.mjs   (add --check to compare semantic colors with the Figma export)
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const t = JSON.parse(readFileSync(join(root, 'design-system/tokens.json'), 'utf8'));
const palette = JSON.parse(readFileSync(join(root, t.primitive.palette), 'utf8'));
const kebab = s => s.replace(/[/.]/g, '-');
const camel = s => s.replace(/[-/. ]+([a-z0-9])/gi, (_, c) => c.toUpperCase()).replace(/^([0-9])/, 'x$1');

// ---------- reference resolution ----------
function primitive(name) {
  if (t.primitive.extra[name]) return t.primitive.extra[name];
  const [ramp, step] = name.split('.');
  const hex = palette[ramp] && palette[ramp][step];
  if (!hex) throw new Error('unknown primitive ' + name);
  return hex;
}
// returns { hex: '#rrggbb', a: 0..1 }
function color(ref, mode) {
  const m = /^\{([^}]+)\}(?:@(\d+))?$/.exec(ref);
  if (!m) throw new Error('not a color reference: ' + ref);
  const [, path, alpha] = m;
  let c;
  if (path.startsWith('color.')) c = color(t.color[mode][path.slice(6)], mode);
  else if (path.startsWith('component.')) c = color(t.component.color[path.slice(10)], mode);
  else c = { hex: primitive(path), a: 1 };
  return alpha ? { hex: c.hex, a: c.a * Number(alpha) / 100 } : c;
}
function dimension(v) {
  if (typeof v === 'number') return v;
  const m = /^\{(space|radius|size)\.([^}]+)\}$/.exec(v);
  if (!m) throw new Error('not a dimension reference: ' + v);
  const val = t[m[1]][m[2]];
  if (val === undefined) throw new Error('unknown dimension ' + v);
  return val;
}
const modes = ['light', 'dark'];
const semantic = mode => Object.fromEntries(Object.entries(t.color[mode]).map(([k, v]) => [k, color(v, mode)]));
const componentColors = mode => Object.fromEntries(Object.entries(t.component.color).map(([k, v]) => [k, color(v, mode)]));
const dims = Object.fromEntries(Object.entries(t.component.dimension).map(([k, v]) => [k, dimension(v)]));

