const sc = ({ hex, a }) => `Color(.sRGB, red: ${(parseInt(hex.slice(1, 3), 16) / 255).toFixed(4)}, green: ${(parseInt(hex.slice(3, 5), 16) / 255).toFixed(4)}, blue: ${(parseInt(hex.slice(5, 7), 16) / 255).toFixed(4)}, opacity: ${+a.toFixed(3)})`;
const swift = ['// Generated by design-system/build-tokens.mjs from tokens.json. Do not edit.', 'import SwiftUI', ''];
swift.push('/// Semantic and component colors for one mode (the lock screen uses light, the Dynamic Island dark).');
swift.push('struct TokColors {');
for (const k of Object.keys(t.color.light)) swift.push(`  let ${camel(k)}: Color`);
for (const k of Object.keys(t.component.color)) swift.push(`  let c${camel('-' + k)}: Color`);
for (const mode of modes) {
  const args = [...Object.entries(semantic(mode)).map(([k, v]) => `${camel(k)}: ${sc(v)}`), ...Object.entries(componentColors(mode)).map(([k, v]) => `c${camel('-' + k)}: ${sc(v)}`)];
  swift.push(`  static let ${mode} = TokColors(`, ...args.map((a, i) => `    ${a}${i < args.length - 1 ? ',' : ''}`), '  )');
}
swift.push('}', '');
const swiftGroup = (name, obj) => { swift.push(`enum ${name} {`); for (const [k, v] of Object.entries(obj)) swift.push(`  static let ${camel(k)}: CGFloat = ${v}`); swift.push('}', ''); };
swiftGroup('TokSpace', t.space); swiftGroup('TokRadius', t.radius); swiftGroup('TokSize', t.size); swiftGroup('TokDim', dims);
// The system font at the tokens' sizes and weights (the brand fonts aren't in the widget extension)
const swiftWeight = { 400: 'regular', 500: 'medium', 600: 'semibold', 700: 'bold' };
swift.push('enum TokText {');
for (const [k, v] of Object.entries(t.text)) swift.push(`  static let ${camel(k)} = Font.system(size: ${v.size}, weight: .${swiftWeight[v.weight]})`);
swift.push('}', '');
mkdirSync(join(root, 'app/ios/PollWidget'), { recursive: true });
writeFileSync(join(root, 'app/ios/PollWidget/Tokens.swift'), swift.join('\n') + '\n');

