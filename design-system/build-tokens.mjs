// ---------- CSS ----------
const rgba = ({ hex, a }) => a === 1 ? hex : `rgb(${parseInt(hex.slice(1, 3), 16)} ${parseInt(hex.slice(3, 5), 16)} ${parseInt(hex.slice(5, 7), 16)} / ${+a.toFixed(3)})`;
const shadowCss = (list, inset) => list.map(([x, y, b, s, c]) => `${inset ? 'inset ' : ''}${x}px ${y}px ${b}px ${s}px ${rgba(color(c, 'light'))}`).join(', ');
const css = ['/* Generated by design-system/build-tokens.mjs from tokens.json. Do not edit. */'];
for (const mode of modes) {
  css.push(mode === 'light' ? ':root {' : '[data-theme="dark"] {');
  for (const [k, v] of Object.entries(semantic(mode))) css.push(`  --color-${kebab(k)}: ${rgba(v)};`);
  for (const [k, v] of Object.entries(componentColors(mode))) css.push(`  --c-${kebab(k)}: ${rgba(v)};`);
  if (mode === 'light') {
    for (const [k, v] of Object.entries(t.space)) css.push(`  --space-${k}: ${v}px;`);
    for (const [k, v] of Object.entries(t.radius)) css.push(`  --radius-${k}: ${v}px;`);
    for (const [k, v] of Object.entries(t.size)) css.push(`  --size-${k}: ${v}px;`);
    css.push(`  --font-sans: '${t.font.sans}', system-ui, sans-serif;`, `  --font-display: '${t.font.display}', '${t.font.sans}', sans-serif;`);
    for (const [k, v] of Object.entries(t.text)) css.push(`  --text-${k}: ${v.size}px;`, `  --text-${k}--line-height: ${v.line}px;`, `  --text-${k}--font-weight: ${v.weight};`);
    for (const [k, v] of Object.entries(t.weight)) css.push(`  --font-weight-${k}: ${v};`);
    for (const [k, v] of Object.entries(t.shadow)) if (!k.startsWith('$')) css.push(`  --shadow-${k}: ${shadowCss(v)};`);
    // the same shadows as filter chains, for shapes that aren't boxes (pin tail, edge arrow)
    for (const [k, v] of Object.entries(t.shadow)) if (!k.startsWith('$')) css.push(`  --filter-${k}: ${v.map(([x, y, b, , c]) => `drop-shadow(${x}px ${y}px ${b / 2}px ${rgba(color(c, 'light'))})`).join(' ')};`);
    for (const [k, v] of Object.entries(t.inset)) if (!k.startsWith('$')) css.push(`  --inset-${k}: ${shadowCss(v, true)};`);
    for (const [k, v] of Object.entries(dims)) css.push(`  --d-${kebab(k)}: ${/(fade-start|scale|tilt|opacity)$/.test(k) ? v : v + 'px'};`);
    const bez = a => `cubic-bezier(${a.join(', ')})`;
    css.push(`  --ease-out: ${bez(t.motion['ease-out'])};`, `  --ease-in-out: ${bez(t.motion['ease-in-out'])};`, `  --ease-drawer: ${bez(t.motion['ease-drawer'])};`, `  --ease-breathe: ${bez(t.motion['ease-breathe'])};`);
    css.push(`  --crossfade-blur: ${t.motion['crossfade-blur']}px;`, `  --enter-blur: ${t.motion['enter-blur']}px;`, `  --morph-enter-scale: ${t.motion['morph-enter-scale']};`, `  --page-zoom-scale: ${t.motion['page-zoom-scale']};`, `  --stagger-ms: ${t.motion['stagger-ms']}ms;`, `  --open-delay-ms: ${t.motion['open-delay-ms']}ms;`, `  --open-stagger-ms: ${t.motion['open-stagger-ms']}ms;`, `  --open-item-ms: ${t.motion['open-item-ms']}ms;`, `  --fold-ms: ${t.motion['fold-ms']}ms;`, `  --enter-ms: ${t.motion['enter-ms']}ms;`, `  --page-enter-delay-ms: ${t.motion['page-enter-delay-ms']}ms;`, `  --toast-ms: ${t.motion['toast-ms']}ms;`, `  --toast-action-ms: ${t.motion['toast-action-ms']}ms;`, `  --settle-ms: ${t.motion['settle-ms']}ms;`, `  --pulse-ms: ${t.motion['pulse-ms']}ms;`, `  --scan-find-ms: ${t.motion['scan-find-ms']}ms;`, `  --scan-read-ms: ${t.motion['scan-read-ms']}ms;`, `  --press-scale: ${t.motion['press-scale']};`, `  --press-ms: ${t.motion['press-ms']}ms;`, `  --fade-ms: ${t.motion['fade-ms']}ms;`, `  --pin-out-ms: ${t.motion['pin-out-ms']}ms;`, `  --pin-in-at: ${t.motion['pin-in-at']};`, `  --pin-mini-at: ${t.motion['pin-mini-at']};`);
  }
  css.push('}');
}
for (const [k, v] of Object.entries(t.text)) {
  css.push(`.text-${k} { font-family: var(--font-${v.font}); font-size: var(--text-${k}); line-height: var(--text-${k}--line-height); font-weight: var(--text-${k}--font-weight); letter-spacing: 0; }`);
}
for (const [k, v] of Object.entries(t.weight)) css.push(`.weight-${k} { font-weight: var(--font-weight-${k}); }`);
mkdirSync(join(root, 'storybook/src'), { recursive: true });
writeFileSync(join(root, 'storybook/src/tokens.css'), css.join('\n') + '\n');

// ---------- Dart ----------
const dc = ({ hex, a }) => `Color(0x${Math.round(a * 255).toString(16).padStart(2, '0').toUpperCase()}${hex.slice(1).toUpperCase()})`;
const shadowDart = list => `[${list.map(([x, y, b, s, c]) => `BoxShadow(offset: Offset(${x}, ${y}), blurRadius: ${b}, spreadRadius: ${s}, color: ${dc(color(c, 'light'))})`).join(', ')}]`;
const insetDart = list => `[${list.map(([x, y, b, s, c]) => `InsetShadow(offset: Offset(${x}, ${y}), blur: ${b}, spread: ${s}, color: ${dc(color(c, 'light'))})`).join(', ')}]`;
const dart = ['// Generated by design-system/build-tokens.mjs from tokens.json. Do not edit.', "import 'package:flutter/widgets.dart';", ''];
dart.push('/// An inner shadow (Flutter has no inset BoxShadow); painted by InsetShadowPainter.');
dart.push('class InsetShadow {', '  const InsetShadow({required this.offset, required this.blur, required this.spread, required this.color});', '  final Offset offset;', '  final double blur;', '  final double spread;', '  final Color color;', '}', '');
dart.push('/// Semantic and component colors for one mode. Read them through `context.tok` (see theme.dart).');
dart.push('class TokColors {', '  const TokColors._(this._m);', '  final Map<String, Color> _m;', '  Color operator [](String name) => _m[name]!;');
for (const mode of modes) {
  dart.push(`  static const ${mode} = TokColors._({`);
  for (const [k, v] of Object.entries(semantic(mode))) dart.push(`    '${k}': ${dc(v)},`);
  for (const [k, v] of Object.entries(componentColors(mode))) dart.push(`    'c/${k}': ${dc(v)},`);
  dart.push('  });');
}
for (const k of Object.keys(t.color.light)) dart.push(`  Color get ${camel(k)} => _m['${k}']!;`);
for (const k of Object.keys(t.component.color)) dart.push(`  Color get c${camel('-' + k)} => _m['c/${k}']!;`);
dart.push('}', '');
const group = (name, obj) => { dart.push(`abstract final class ${name} {`); for (const [k, v] of Object.entries(obj)) dart.push(`  static const double ${camel(k)} = ${v};`); dart.push('}', ''); };
group('TokSpace', t.space); group('TokRadius', t.radius); group('TokSize', t.size); group('TokDim', dims);
dart.push('abstract final class TokFont {', `  static const sans = '${t.font.sans}';`, `  static const display = '${t.font.display}';`, '}', '');
dart.push('abstract final class TokText {');
for (const [k, v] of Object.entries(t.text)) dart.push(`  static const ${camel(k)} = TextStyle(fontFamily: TokFont.${v.font}, fontSize: ${v.size}, height: ${+(v.line / v.size).toFixed(6)}, fontWeight: FontWeight.w${v.weight}, letterSpacing: 0, leadingDistribution: TextLeadingDistribution.even);`);
dart.push('}', '', 'abstract final class TokWeight {');
for (const [k, v] of Object.entries(t.weight)) dart.push(`  static const ${k} = FontWeight.w${v};`);
dart.push('}', '', 'abstract final class TokShadow {');
for (const [k, v] of Object.entries(t.shadow)) if (!k.startsWith('$')) dart.push(`  static const ${camel(k)} = ${shadowDart(v)};`);
dart.push('}', '', 'abstract final class TokInset {');
for (const [k, v] of Object.entries(t.inset)) if (!k.startsWith('$')) dart.push(`  static const ${camel(k)} = ${insetDart(v)};`);
dart.push('}', '');
dart.push('/// Apple-style spring: perceived duration (s) and bounce (0 = no overshoot).');
dart.push('class TokSpring {', '  const TokSpring(this.duration, this.bounce);', '  final double duration;', '  final double bounce;', '}', '');
dart.push('abstract final class TokMotion {');
for (const k of ['spring-morph', 'spring-expand', 'spring-collapse', 'spring-snap', 'spring-open']) dart.push(`  static const ${camel(k)} = TokSpring(${t.motion[k].duration}, ${t.motion[k].bounce});`);
dart.push(`  static const double crossfadeBlur = ${t.motion['crossfade-blur']};`, `  static const double enterBlur = ${t.motion['enter-blur']};`, `  static const double morphEnterScale = ${t.motion['morph-enter-scale']};`, `  static const double pageZoomScale = ${t.motion['page-zoom-scale']};`, `  static const stagger = Duration(milliseconds: ${t.motion['stagger-ms']});`, `  static const openDelay = Duration(milliseconds: ${t.motion['open-delay-ms']});`, `  static const openStagger = Duration(milliseconds: ${t.motion['open-stagger-ms']});`, `  static const openItem = Duration(milliseconds: ${t.motion['open-item-ms']});`, `  static const fold = Duration(milliseconds: ${t.motion['fold-ms']});`, `  static const int staggerMax = ${t.motion['stagger-max']};`, `  static const enter = Duration(milliseconds: ${t.motion['enter-ms']});`, `  static const pageEnterDelay = Duration(milliseconds: ${t.motion['page-enter-delay-ms']});`, `  static const toast = Duration(milliseconds: ${t.motion['toast-ms']});`, `  static const toastAction = Duration(milliseconds: ${t.motion['toast-action-ms']});`, `  static const settle = Duration(milliseconds: ${t.motion['settle-ms']});`, `  static const pulse = Duration(milliseconds: ${t.motion['pulse-ms']});`, `  static const scanFind = Duration(milliseconds: ${t.motion['scan-find-ms']});`, `  static const scanRead = Duration(milliseconds: ${t.motion['scan-read-ms']});`, `  static const double pressScale = ${t.motion['press-scale']};`, `  static const press = Duration(milliseconds: ${t.motion['press-ms']});`, `  static const fade = Duration(milliseconds: ${t.motion['fade-ms']});`, `  static const pinOut = Duration(milliseconds: ${t.motion['pin-out-ms']});`, `  static const double pinInAt = ${t.motion['pin-in-at']};`, `  static const double pinMiniAt = ${t.motion['pin-mini-at']};`);
for (const k of ['ease-out', 'ease-in-out', 'ease-drawer', 'ease-breathe']) dart.push(`  static const ${camel(k)} = Cubic(${t.motion[k].join(', ')});`);
dart.push('}');
mkdirSync(join(root, 'app/lib/design'), { recursive: true });
writeFileSync(join(root, 'app/lib/design/tokens.dart'), dart.join('\n') + '\n');

